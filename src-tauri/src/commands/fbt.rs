//! FBT Build Studio — clone firmware repos, manage fbt_options_local.py, run builds.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde::{Deserialize, Serialize};
use walkdir::WalkDir;

use crate::error::{FlipperError, Result};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FbtConfig {
    pub firmware_origin: String,
    pub firmware_app_set: String,
    pub extra_int_apps: Vec<String>,
    pub extra_ext_apps: Vec<String>,
    pub update_splash: String,
    pub loader_autostart: String,
    pub extra_defines: Vec<String>,
}

impl Default for FbtConfig {
    fn default() -> Self {
        Self {
            firmware_origin: "DeezFW".into(),
            firmware_app_set: "default".into(),
            extra_int_apps: vec![],
            extra_ext_apps: vec![],
            update_splash: "update_default".into(),
            loader_autostart: String::new(),
            extra_defines: vec![],
        }
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct AppManifestEntry {
    pub appid: String,
    pub name: Option<String>,
    pub apptype: Option<String>,
    pub path: String,
}

#[derive(Debug, Clone, Serialize)]
pub struct FbtArtifact {
    pub path: String,
    pub kind: String,
    pub size_bytes: u64,
    pub modified_secs: u64,
}

#[derive(Debug, Clone, Serialize)]
pub struct FirmwareBase {
    pub id: String,
    pub name: String,
    pub url: String,
}

fn fbt_script(repo: &Path) -> PathBuf {
    #[cfg(windows)]
    {
        let cmd = repo.join("fbt.cmd");
        if cmd.exists() {
            return cmd;
        }
    }
    repo.join("fbt")
}

fn render_fbt_options_local(config: &FbtConfig) -> String {
    let int_apps = config.extra_int_apps.join(",");
    let ext_apps = config.extra_ext_apps.join(",");
    let defines = config
        .extra_defines
        .iter()
        .map(|d| format!("    \"{d}\","))
        .collect::<String>();
    format!(
        r#"# Auto-generated by Deez Flipper Tools — do not edit fbt_options.py
Import("fbt_options")

env = DefaultEnvironment()

env.Append(
    FIRMWARE_ORIGIN="{origin}",
    FIRMWARE_APP_SET="{app_set}",
    UPDATE_SPLASH="{splash}",
    LOADER_AUTOSTART="{autostart}",
)

# Extra apps passed on CLI when building:
# --extra-int-apps={int_apps}
# --extra-ext-apps={ext_apps}
# --extra-define flags:
{defines}
"#,
        origin = config.firmware_origin,
        app_set = config.firmware_app_set,
        splash = config.update_splash,
        autostart = config.loader_autostart,
        int_apps = int_apps,
        ext_apps = ext_apps,
        defines = if defines.is_empty() {
            "    # (none)".to_string()
        } else {
            defines
        },
    )
}

fn parse_simple_fbt_options(content: &str) -> FbtConfig {
    let mut cfg = FbtConfig::default();
    for line in content.lines() {
        let line = line.trim();
        if let Some(v) = line.strip_prefix("FIRMWARE_ORIGIN=") {
            cfg.firmware_origin = v.trim_matches('"').trim_matches('\'').to_string();
        }
        if let Some(v) = line.strip_prefix("FIRMWARE_APP_SET=") {
            cfg.firmware_app_set = v.trim_matches('"').trim_matches('\'').to_string();
        }
        if let Some(v) = line.strip_prefix("UPDATE_SPLASH=") {
            cfg.update_splash = v.trim_matches('"').trim_matches('\'').to_string();
        }
        if let Some(v) = line.strip_prefix("LOADER_AUTOSTART=") {
            cfg.loader_autostart = v.trim_matches('"').trim_matches('\'').to_string();
        }
    }
    cfg
}

